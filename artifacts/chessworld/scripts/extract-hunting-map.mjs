#!/usr/bin/env node
/**
 * Extracts the hunting-related geometry of crafting-world.tmj into a shared TS
 * module consumed by the SERVER (animal AI has no access to the TMJ at runtime)
 * and by the admin page (anchor counters).
 *
 *   node artifacts/chessworld/scripts/extract-hunting-map.mjs
 *
 * Output: server/src/shared/hunting/craftingWorldMapData.ts — remember to mirror
 * it to artifacts/api-server/src/src/shared and artifacts/chessworld/src/shared.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const tmjPath = resolve(root, 'artifacts/chessworld/public/assets/CraftingWorld/map/crafting-world.tmj');
const outPath = resolve(root, 'server/src/shared/hunting/craftingWorldMapData.ts');

const map = JSON.parse(readFileSync(tmjPath, 'utf8'));

function* objectLayers(layers) {
  for (const layer of layers) {
    if (layer.type === 'group') yield* objectLayers(layer.layers ?? []);
    else if (layer.type === 'objectgroup') yield layer;
  }
}
const byName = new Map();
for (const layer of objectLayers(map.layers)) byName.set(layer.name, layer.objects ?? []);

const r = (n) => Math.round(n * 100) / 100;
const points = (layerName, prefix) =>
  (byName.get(layerName) ?? [])
    .filter((o) => typeof o.name === 'string' && o.name.startsWith(prefix))
    .sort((a, b) => Number(a.name.slice(prefix.length)) - Number(b.name.slice(prefix.length)))
    .map((o) => ({ name: o.name, x: r(o.x), y: r(o.y) }));

const residentAnchors = points('resident_animals', 'resident_animal_');
const huntAnchors = points('hunt_animals', 'hunt_animal_');
const monsterTreeAnchors = points('monster_tree', 'monster_tree_');
const safeObj = (byName.get('safe_zone') ?? []).find((o) => o.name === 'safe_zone' && o.width > 0);
if (!safeObj) throw new Error('safe_zone rectangle not found');
const safeZone = { x: r(safeObj.x), y: r(safeObj.y), width: r(safeObj.width), height: r(safeObj.height) };
// Tiled rectangles: x/y = top-left, rotation in clockwise degrees around that corner.
const collisionRects = (byName.get('collisions') ?? [])
  .filter((o) => (o.width ?? 0) > 0 && (o.height ?? 0) > 0 && !o.point && !o.polygon && !o.ellipse)
  .map((o) => [r(o.x), r(o.y), r(o.width), r(o.height), r(o.rotation ?? 0)]);

const out = `// GENERATED by artifacts/chessworld/scripts/extract-hunting-map.mjs — do not edit by hand.
// Source: public/assets/CraftingWorld/map/crafting-world.tmj
export interface MapAnchor { name: string; x: number; y: number }
export interface MapRect { x: number; y: number; width: number; height: number }
/** [x, y, width, height, rotationDeg] — Tiled rectangle, rotation clockwise around the top-left corner. */
export type MapCollisionRect = readonly [number, number, number, number, number];

export const CRAFTING_WORLD_MAP = {
  widthPx: ${map.width * map.tilewidth},
  heightPx: ${map.height * map.tileheight},
  tileSize: ${map.tilewidth},
  safeZone: ${JSON.stringify(safeZone)} as MapRect,
  residentAnchors: ${JSON.stringify(residentAnchors)} as readonly MapAnchor[],
  huntAnchors: ${JSON.stringify(huntAnchors)} as readonly MapAnchor[],
  monsterTreeAnchors: ${JSON.stringify(monsterTreeAnchors)} as readonly MapAnchor[],
  collisionRects: ${JSON.stringify(collisionRects)} as readonly MapCollisionRect[],
} as const;
`;
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`wrote ${outPath}: residents=${residentAnchors.length} hunts=${huntAnchors.length} trees=${monsterTreeAnchors.length} collisions=${collisionRects.length}`);
